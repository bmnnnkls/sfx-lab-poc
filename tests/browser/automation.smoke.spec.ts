import { serializeProject } from '../../src/core'
import { test, expect, expectSaved, expectSound } from './fixtures'
import { sweepProject } from './automation-project'

test('draws, edits, undoes and reloads a looping filter sweep', async ({ page }, info) => {
  await page.addInitScript((saved) => { if (!localStorage.getItem('sfxlab:project')) localStorage.setItem('sfxlab:project', saved) }, serializeProject(sweepProject(true)))
  await page.goto('/')
  await page.getByRole('button', { name: 'Edit Sweep clip', exact: true }).click()
  await page.getByRole('button', { name: 'Automation', exact: true }).click()
  const area = page.getByRole('application', { name: 'Automation drawing area' })
  await expect(area).toBeVisible()
  const box = await area.boundingBox(); if (!box) throw new Error('No automation drawing area')
  await page.mouse.click(box.x + box.width * 0.125, box.y + box.height * 0.85)
  await page.mouse.click(box.x + box.width * 0.75, box.y + box.height * 0.15)
  await expect(page.locator('[data-point-id]')).toHaveCount(2)
  const point = page.locator('[data-point-id]').last(), bounds = await point.boundingBox(); if (!bounds) throw new Error('No point')
  await page.mouse.move(bounds.x + bounds.width / 2, bounds.y + bounds.height / 2); await page.mouse.down()
  await page.mouse.move(box.x + box.width * 0.875, box.y + box.height * 0.25, { steps: 10 }); await page.mouse.up()
  await expect(page.getByLabel('Point beat', { exact: true })).toHaveValue('1.75')
  await page.getByRole('button', { name: 'Undo', exact: true }).click()
  await expect(page.getByLabel('Point beat', { exact: true })).toHaveValue('1.5')
  await page.getByRole('button', { name: 'Redo', exact: true }).click()
  await expect(page.getByLabel('Point beat', { exact: true })).toHaveValue('1.75')
  await page.getByRole('button', { name: 'Launch scene 1', exact: true }).click(); await expectSound(page)
  await expectSaved(page)
  const saved = await page.evaluate(() => localStorage.getItem('sfxlab:project'))
  await page.waitForTimeout(1200)
  expect(await page.evaluate(() => localStorage.getItem('sfxlab:project'))).toBe(saved)
  await page.screenshot({ path: info.outputPath('automation-editor.png') })
  await page.getByRole('button', { name: 'Stop', exact: true }).first().click()
  await page.reload()
  await page.getByRole('button', { name: 'Edit Sweep clip', exact: true }).click()
  await page.getByRole('button', { name: 'Automation', exact: true }).click()
  await expect(page.locator('[data-point-id]')).toHaveCount(2)
  await page.getByRole('button', { name: 'Instrument', exact: true }).click()
  await page.getByRole('button', { name: 'Sweep', exact: true }).click()
})

test('edits return/master slots, resizes with undo and reloads without playback saves', async ({ page }, info) => {
  const { slotSweepProject } = await import('./automation-project')
  await page.addInitScript((saved) => { if (!localStorage.getItem('sfxlab:project')) localStorage.setItem('sfxlab:project', saved) }, serializeProject(slotSweepProject()))
  await page.goto('/')
  await page.getByRole('button', { name: 'Edit Master automation scene 1', exact: true }).click()
  await expect(page.getByLabel('Automation loop beats')).toHaveValue('3')
  await expect(page.locator('[data-point-id]')).toHaveCount(2)
  await page.getByLabel('Automation loop beats').fill('1')
  await page.getByLabel('Automation loop beats').blur()
  await expect(page.locator('[data-point-id]')).toHaveCount(1)
  await page.getByRole('button', { name: 'Undo', exact: true }).click()
  await expect(page.getByLabel('Automation loop beats')).toHaveValue('3')
  await expect(page.locator('[data-point-id]')).toHaveCount(2)
  await page.getByRole('button', { name: 'Edit Throw automation scene 1', exact: true }).click()
  await expect(page.getByLabel('Automation loop beats')).toHaveValue('1')
  await page.getByRole('button', { name: 'Create Master automation scene 2', exact: true }).click()
  await expect(page.getByLabel('Automation loop beats')).toHaveValue('4')
  await page.getByRole('button', { name: 'Delete slot', exact: true }).click()
  await expect(page.getByText(/Empty automation slot:/)).toBeVisible()
  await page.getByRole('button', { name: 'Undo', exact: true }).click()
  await expect(page.getByLabel('Automation loop beats')).toHaveValue('4')
  await page.getByRole('button', { name: 'Launch scene 1', exact: true }).click()
  await expectSound(page)
  await expect(page.locator('[data-automation-owner="Master"][data-scene="0"]')).toHaveClass(/playing/)
  await expect(page.locator('[data-automation-owner="Throw"][data-scene="0"]')).toHaveClass(/playing/)
  await page.getByRole('button', { name: 'Stop Master automation scene 1', exact: true }).click()
  await expect(page.locator('[data-automation-owner="Master"][data-scene="0"]')).not.toHaveClass(/playing/)
  await expect(page.locator('[data-automation-owner="Throw"][data-scene="0"]')).toHaveClass(/playing/)
  await page.getByRole('button', { name: 'Launch Master automation scene 1', exact: true }).click()
  await expect(page.locator('[data-automation-owner="Master"][data-scene="0"]')).toHaveClass(/playing/)
  await expectSaved(page)
  const saved = await page.evaluate(() => localStorage.getItem('sfxlab:project'))
  await page.waitForTimeout(1200)
  expect(await page.evaluate(() => localStorage.getItem('sfxlab:project'))).toBe(saved)
  await page.getByRole('button', { name: 'Edit Master automation scene 1', exact: true }).click()
  await page.screenshot({ path: info.outputPath('automation-slots.png') })
  await page.getByRole('button', { name: 'Stop', exact: true }).first().click()
  await expect(page.locator('[data-automation-owner="Master"][data-scene="0"]')).not.toHaveClass(/playing/)
  await page.reload()
  await page.getByRole('button', { name: 'Edit Master automation scene 1', exact: true }).click()
  await expect(page.getByLabel('Automation loop beats')).toHaveValue('3')
  await expect(page.locator('[data-point-id]')).toHaveCount(2)
})
