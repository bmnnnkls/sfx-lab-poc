import { test, expect, expectSaved, openView, viewRoot } from '../support/fixtures'
import { installMidiPorts, sendMidi } from '../support/midi-ports'

for (const mode of ['denied', 'unsupported'] as const) test(`MIDI ${mode} remains usable and only requests from Enable`, async ({ page }) => {
  await installMidiPorts(page, mode)
  await page.goto('/')
  expect(await page.evaluate(() => window.__midiTest.requests)).toBe(0)
  await page.getByRole('button', { name: 'MIDI', exact: true }).click()
  expect(await page.evaluate(() => window.__midiTest.requests)).toBe(0)
  await page.getByRole('button', { name: 'Enable MIDI', exact: true }).click()
  await expect(page.getByRole('region', { name: 'MIDI settings', exact: true })).toContainText(`MIDI: ${mode}`)
  await page.getByRole('button', { name: 'Close MIDI settings' }).click()
  await page.getByLabel('Project name').fill('Still usable')
  await expect(page.getByLabel('Project name')).toHaveValue('Still usable')
})

test('Low Light filter learn, pickup, undo, reload, reassignment, rebind and removal', async ({ page }) => {
  await installMidiPorts(page)
  await page.goto('/')
  await page.getByRole('button', { name: 'MIDI', exact: true }).click()
  await page.getByRole('button', { name: 'Enable MIDI', exact: true }).click()
  await expect(page.getByRole('region', { name: 'MIDI settings', exact: true })).toContainText('Test keyboard — connected')
  await page.getByRole('button', { name: 'Close MIDI settings' }).click()
  const showFilter = async () => {
    await viewRoot(page, 'Session').getByText('Master', { exact: true }).first().click()
    await openView(page, 'Effects')
    await page.getByRole('group', { name: 'View', exact: true }).getByRole('button', { name: 'Panel', exact: true }).click()
    return page.getByRole('slider', { name: 'DJ filter', exact: true })
  }
  const filter = await showFilter()
  const initial = await filter.getAttribute('aria-valuenow')
  await filter.click({ button: 'right' })
  await page.getByRole('menuitem', { name: 'MIDI learn', exact: true }).click()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('button', { name: 'Cancel MIDI learn' })).toHaveCount(0)
  await filter.click({ button: 'right' }); await page.getByRole('menuitem', { name: 'MIDI learn', exact: true }).click()
  await sendMidi(page, [0xb0, 64, 127])
  await expect(page.getByRole('button', { name: 'Cancel MIDI learn' })).toBeVisible()
  await sendMidi(page, [0xb0, 21, 0])
  await expect(filter).toHaveAttribute('aria-valuenow', initial!)
  await sendMidi(page, [0xb0, 21, 0]); await expect(filter).toHaveAttribute('aria-valuenow', initial!)
  await sendMidi(page, [0xb0, 21, 127]); await expect(filter).not.toHaveAttribute('aria-valuenow', initial!)
  const edited = await filter.getAttribute('aria-valuenow')
  await page.getByRole('button', { name: 'Undo', exact: true }).click(); await expect(filter).toHaveAttribute('aria-valuenow', initial!)
  await page.getByRole('button', { name: 'Redo', exact: true }).click(); await expect(filter).toHaveAttribute('aria-valuenow', edited!)
  await expectSaved(page); await page.reload()
  const reloaded = await showFilter(); await expect(reloaded).toHaveAttribute('aria-valuenow', edited!)
  await page.getByRole('button', { name: 'MIDI', exact: true }).click()
  await expect(page.getByTestId('midi-mapping')).toHaveCount(1)
  await expect(page.getByTestId('midi-mapping')).toContainText('unavailable')
  await page.getByRole('button', { name: 'Enable MIDI', exact: true }).click()
  await page.getByLabel('Input for CC 21').selectOption('other')
  await expect(page.getByLabel('Input for CC 21')).toHaveValue('other')
  await page.evaluate(() => window.__midiTest.connected('other', false))
  await expect(page.getByTestId('midi-mapping')).toContainText('Device unavailable')
  await page.evaluate(() => window.__midiTest.connected('other', true))
  await page.getByRole('button', { name: 'Learn again', exact: true }).click(); await sendMidi(page, [0xb0, 22, 0], 'other')
  await expect(page.getByTestId('midi-mapping')).toContainText('CC 22')
  await page.getByRole('button', { name: 'Close MIDI settings' }).click()
  await openView(page, 'Mixer')
  const fader = page.getByRole('slider', { name: 'Master fader', exact: true })
  await fader.click({ button: 'right' }); await page.getByRole('menuitem', { name: 'MIDI learn', exact: true }).click()
  await sendMidi(page, [0xb0, 22, 0], 'other')
  await expect(page.getByRole('button', { name: 'Reassign', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Cancel MIDI learn', exact: true }).click()
  await fader.click({ button: 'right' }); await page.getByRole('menuitem', { name: 'MIDI learn', exact: true }).click()
  await sendMidi(page, [0xb0, 22, 0], 'other')
  await page.getByRole('button', { name: 'Reassign', exact: true }).click()
  await page.getByRole('button', { name: 'MIDI', exact: true }).click()
  await expect(page.getByTestId('midi-mapping')).toHaveCount(1)
  await expect(page.getByTestId('midi-mapping')).toContainText('Master / volume')
  await page.getByRole('button', { name: 'Remove mapping', exact: true }).click()
  await expect(page.getByTestId('midi-mapping')).toHaveCount(0)
  await page.getByRole('button', { name: 'Disable MIDI', exact: true }).click()
  await expect(page.getByRole('region', { name: 'MIDI settings', exact: true })).toContainText('MIDI: disabled')
})

test("a track's own MIDI input is set in MIDI settings, tagged on its header, undone, and kept on reload", async ({ page }) => {
  await installMidiPorts(page)
  await page.goto('/')
  await page.getByRole('button', { name: 'MIDI', exact: true }).click()
  await page.getByRole('button', { name: 'Enable MIDI', exact: true }).click()
  const settings = page.getByRole('region', { name: 'MIDI settings', exact: true })
  await expect(settings).toContainText('Test keyboard — connected')
  const input = settings.getByLabel('MIDI input of Drone'), channel = settings.getByLabel('MIDI channel of Drone')
  await expect(input).toHaveValue('follow')
  await expect(channel).toBeDisabled()
  await input.selectOption({ label: 'Test keyboard' })
  await channel.selectOption({ value: '9' })
  await expect(settings.getByTestId('midi-track-input').filter({ hasText: 'Drone' })).toContainText('Always listens: Test keyboard, channel 10')
  await page.getByRole('button', { name: 'Close MIDI settings' }).click()
  const header = viewRoot(page, 'Session').getByRole('button', { name: 'Drone midi 10', exact: true })
  await expect(header).toBeVisible()
  await page.getByRole('button', { name: 'Undo', exact: true }).click()
  await expect(viewRoot(page, 'Session').getByRole('button', { name: 'Drone midi', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Redo', exact: true }).click()
  await expect(header).toBeVisible()
  await expectSaved(page); await page.reload()
  await expect(viewRoot(page, 'Session').getByRole('button', { name: 'Drone midi 10', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'MIDI', exact: true }).click()
  // Not enabled after a reload: the saved input is shown by its name, as unavailable.
  await expect(page.getByLabel('MIDI input of Drone')).toHaveValue('keys')
  await page.getByLabel('MIDI input of Drone').selectOption('follow')
  await expect(page.getByLabel('MIDI channel of Drone')).toBeDisabled()
  await page.getByRole('button', { name: 'Close MIDI settings' }).click()
  await expect(viewRoot(page, 'Session').getByRole('button', { name: 'Drone', exact: true })).toBeVisible()
})
