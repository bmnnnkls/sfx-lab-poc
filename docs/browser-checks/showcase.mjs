// The two shipped example projects (Low Light, Glass Rain): the first-run welcome, the Examples menu, playing them, and the gestures
// that make them worth playing with (an XY pad, Randomize with undo, the master's Cut and Hush buttons).
import { createRequire } from 'node:module'
import { existsSync } from 'node:fs'
const require = createRequire(existsSync('/node-tools/node_modules/') ? '/node-tools/node_modules/' : '/opt/node-tools/node_modules/')
const { chromium } = require('playwright')
const dir = process.argv[2] ?? '.'
const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium', args: ['--no-sandbox', '--autoplay-policy=no-user-gesture-required'] })
const page = await (await browser.newContext({ viewport: { width: 1500, height: 1000 } })).newPage()
const errors = []
page.on('pageerror', (e) => errors.push(String(e)))
page.on('console', (m) => m.type() === 'error' && errors.push(m.text()))
const check = (label, ok, extra = '') => console.log(`${ok ? 'PASS' : 'FAIL'}  ${label} ${extra}`)

const projectName = () => page.getByLabel('Project name').inputValue()
/** The names in the session header: clip tracks, then returns ("Hall return"), then the Master strip. */
const trackNames = () => page.locator('[class*="_trackName_"]').allTextContents()
const tab = (name) => page.getByRole('button', { name, exact: true }).first().click()
const view = (name) => page.getByRole('group', { name: 'View' }).getByRole('button', { name, exact: true }).click()
const track = (name) => page.locator('[class*="_trackName_"]', { hasText: new RegExp(`^${name}$`) }).first().click()
const pad = (name) => page.getByRole('group', { name, exact: true })
const padAt = async (name) => ({ x: Number(await pad(name).getAttribute('data-x')), y: Number(await pad(name).getAttribute('data-y')) })
const loudest = async (ms) => { let m = 0; const end = Date.now() + ms; while (Date.now() < end) { m = Math.max(m, Number(await page.locator('[data-peak]').first().getAttribute('data-peak'))); await page.waitForTimeout(40) } return m }
const openExample = async (title) => { if ((await page.locator('details[open]').count()) === 0) await page.getByText('File', { exact: true }).click(); await page.getByRole('button', { name: new RegExp(title) }).click() }
const clearStorage = () => page.evaluate(async () => { localStorage.clear(); localStorage.setItem('sfxlab:editor-height', '560'); await new Promise((r) => { const q = indexedDB.deleteDatabase('sfxlab'); q.onsuccess = q.onerror = q.onblocked = () => r() }) })

// ---- a first visit opens on Low Light and says how to start
await page.goto('http://localhost:4173/')
await clearStorage()
await page.reload()
await page.waitForTimeout(500)
check('a first visit opens on Low Light', (await projectName()) === 'Low Light')
const names = await trackNames()
check('with its thirteen clip tracks, three returns and the master', names.length === 17 && names.includes('Kick') && names.includes('Knocks') && names.includes('Hall return') && names.includes('Master'), JSON.stringify(names))
const welcome = page.getByRole('status').filter({ hasText: 'Welcome: "Low Light"' })
check('a welcome note says what to try', (await welcome.count()) === 1 && (await welcome.innerText()).includes('scene 1'))
await page.screenshot({ path: `${dir}/showcase-welcome.png` })
await page.getByRole('button', { name: 'Dismiss' }).click()
await page.reload()
await page.waitForTimeout(400)
check('the welcome comes once: a reload with nothing edited opens the same project without it', (await projectName()) === 'Low Light' && (await page.getByRole('status').filter({ hasText: 'Welcome' }).count()) === 0)

// ---- ?starter keeps the three plain tracks
await page.goto('http://localhost:4173/?starter')
await clearStorage()
await page.reload()
const starterNames = await trackNames()
check('?starter opens the three-track starter instead', (await projectName()) === 'Demo project' && starterNames.length === 4 && starterNames.includes('Bass'), JSON.stringify(starterNames))

// ---- the Examples menu
await page.goto('http://localhost:4173/')
await clearStorage()
await page.reload()
await page.getByRole('button', { name: 'Dismiss' }).click()
check('the scenes are named under their launch buttons', (await page.getByRole('button', { name: 'Launch scene 7, Drop' }).count()) === 1)
await page.getByText('File', { exact: true }).click()
const items = await page.locator('details[open] button').allTextContents()
check('File lists both examples and the starter', ['Low Light', 'Glass Rain', 'Starter'].every((t) => items.some((i) => i.startsWith(t))), JSON.stringify(items))
await openExample('Glass Rain')
await page.waitForTimeout(400)
check('Glass Rain replaces the project', (await projectName()) === 'Glass Rain' && (await trackNames()).includes('Bells'))
const loaded = page.getByRole('status').filter({ hasText: 'Loaded "Glass Rain"' })
check('and says how to play it, in a note that stays long enough to read', (await loaded.count()) === 1 && (await loaded.innerText()).includes('Randomize') && (await loaded.innerText()).includes('Hush'))
await page.getByRole('button', { name: 'Dismiss' }).click()

// ---- it plays: scene 4 (Garden)
await page.getByRole('button', { name: 'Launch scene 4' }).click()
const heard = await loudest(5000)
check('scene 4 of Glass Rain makes sound in the real engine', heard > 0.02, `peak ${heard.toFixed(3)}`)

// ---- the Bells panel: an XY pad moves two things at once; Randomize composes something else and Undo takes it back
await track('Bells')
await tab('Instrument')
await view('Panel')
const feel = 'Density / Restlessness'
check('Bells has its XY pad on the panel', (await pad(feel).count()) === 1)
const before = await padAt(feel)
const box = await pad(feel).boundingBox()
await page.mouse.move(box.x + box.width * 0.5, box.y + box.height * 0.5)
await page.mouse.down()
await page.mouse.move(box.x + box.width * 0.85, box.y + box.height * 0.2, { steps: 6 })
await page.mouse.up()
const moved = await padAt(feel)
check('dragging the pad moves both axes', Math.abs(moved.x - before.x) > 0.05 && Math.abs(moved.y - before.y) > 0.05, JSON.stringify([before, moved]))
await page.getByRole('button', { name: 'Undo' }).click()
check('and one undo puts the pad back', Math.abs((await padAt(feel)).x - before.x) < 0.01)
await page.getByRole('button', { name: 'Randomize', exact: true }).click()
const rolled = await padAt(feel)
check('Randomize re-rolls the pad (and its seeds)', Math.abs(rolled.x - before.x) > 0.001 || Math.abs(rolled.y - before.y) > 0.001, JSON.stringify([before, rolled]))
const still = await loudest(2500)
check('and the track still sounds afterwards', still > 0.02, `peak ${still.toFixed(3)}`)
await page.getByRole('button', { name: 'Undo' }).click()
check('Randomize is one undo step', Math.abs((await padAt(feel)).x - before.x) < 0.01)

// ---- the arp listens to the pad: its notes tab shows the chain
await track('Arp')
await tab('Notes')
await view('Graph')
const surface = page.getByTestId('patch-surface')
const noteNodes = await surface.locator('[data-testid^="node-"]').count()
check("the arp's note graph is the chain from the pad's notes to the instrument", noteNodes >= 6, `${noteNodes} nodes`)
await page.screenshot({ path: `${dir}/showcase-arp-notes.png` })

// ---- Hush on the master panel
await page.locator('[class*="grid"], [class*="session"]').first().evaluate((el) => { el.scrollLeft = 99999 }).catch(() => {})
await page.getByText('Master', { exact: true }).first().click()
await tab('Effects')
await view('Panel')
const hush = page.getByRole('switch', { name: 'Hush' })
check('the master panel has a Hush switch', (await hush.count()) === 1)
const normal = await loudest(1500)
await hush.click()
await page.waitForTimeout(3500)
const hushed = await loudest(1200)
check('Hush fades the whole piece down', hushed < normal * 0.4, `${normal.toFixed(3)} -> ${hushed.toFixed(3)}`)
await hush.click()
await page.screenshot({ path: `${dir}/showcase-glass-master.png` })

// ---- Low Light: the drop, the DJ filter slider and the Cut button
await openExample('Low Light')
await page.waitForTimeout(400)
await page.getByRole('button', { name: 'Dismiss' }).click().catch(() => {})
await page.locator('[class*="grid"], [class*="session"]').first().evaluate((el) => { el.scrollLeft = 99999 }).catch(() => {})
await page.getByRole('button', { name: 'Launch scene 7' }).click()
await page.getByText('Master', { exact: true }).first().click()
await tab('Effects')
await view('Panel')
const dj = page.getByRole('slider', { name: 'DJ filter', exact: true })
check('the master panel has the DJ filter slider and a Cut button', (await dj.count()) === 1 && (await page.getByRole('switch', { name: 'Cut (hold)' }).count()) === 1)
const drop = await loudest(4500)
check('the drop plays loud and with headroom', drop > 0.2 && drop < 0.95, `peak ${drop.toFixed(3)}`)
await dj.focus()
for (let i = 0; i < 30; i++) await page.keyboard.press('ArrowLeft')
await page.waitForTimeout(1500)
const closed = await loudest(1500)
check('pulling the DJ filter left takes the top off, and the mix gets quieter', closed < drop, `${drop.toFixed(3)} -> ${closed.toFixed(3)}`)
await page.screenshot({ path: `${dir}/showcase-lowlight-master.png` })
for (let i = 0; i < 30; i++) await page.keyboard.press('ArrowRight')
const cut = page.getByRole('switch', { name: 'Cut (hold)' })
const cutBox = await cut.boundingBox()
await page.mouse.move(cutBox.x + cutBox.width / 2, cutBox.y + cutBox.height / 2)
await page.mouse.down()
await page.waitForTimeout(700)
const cutting = await loudest(600)
await page.mouse.up()
await page.waitForTimeout(500)
const back = await loudest(1500)
check('holding Cut silences the mix, and letting go brings it back', cutting < 0.02 && back > 0.15, `${cutting.toFixed(4)} then ${back.toFixed(3)}`)

// ---- every panel of every track opens without a problem
const failures = []
for (const name of ['Kick', 'Clap', 'Hat', 'Open hat', 'Shaker', 'Knocks', 'Bass', 'Stab', 'Arp', 'Drone', 'Riser', 'Crash', 'Dust']) {
  await page.evaluate(() => { const el = document.querySelector('[class*="grid"], [class*="session"]'); if (el) el.scrollLeft = 0 })
  const header = page.locator('[class*="_trackName_"]', { hasText: new RegExp(`^${name}$`) }).first()
  await header.scrollIntoViewIfNeeded()
  await header.click()
  await tab('Instrument')
  await view('Panel')
  const knobs = await page.getByRole('slider').count()
  if (knobs < 3) failures.push(`${name}: ${knobs}`)
}
check('every track of Low Light has a panel of knobs', failures.length === 0, JSON.stringify(failures))
check('no errors in the console', errors.length === 0, JSON.stringify(errors.slice(0, 3)))
await browser.close()
