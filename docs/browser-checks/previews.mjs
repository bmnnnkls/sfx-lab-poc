import { createRequire } from 'node:module'
import { existsSync } from 'node:fs'
const require = createRequire(existsSync('/node-tools/node_modules/') ? '/node-tools/node_modules/' : '/opt/node-tools/node_modules/')
const { chromium } = require('playwright')
const dir = process.argv[2] ?? '.'
const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium', args: ['--no-sandbox', '--autoplay-policy=no-user-gesture-required'] })
const context = await browser.newContext({ viewport: { width: 1500, height: 1000 } })
const page = await context.newPage()
const errors = []
page.on('pageerror', (e) => errors.push(String(e)))
page.on('console', (m) => m.type() === 'error' && errors.push(m.text()))
const check = (label, ok, extra = '') => console.log(`${ok ? 'PASS' : 'FAIL'}  ${label} ${extra}`)

const surface = page.getByTestId('patch-surface')
const track = (name) => page.locator('[class*="_trackName_"]', { hasText: name }).first().click()
const node = (title) => surface.locator('[data-testid^="node-"]').filter({ has: page.locator('[class*="nodeTitle"]', { hasText: new RegExp(`^${title}`) }) }).first()
const idOf = async (title) => (await node(title).getAttribute('data-testid')).replace(/^node-/, '')
const properties = () => page.getByRole('complementary', { name: 'Properties' })
const selectNode = (title) => node(title).locator('[class*="nodeHeader"]').first().click()
const valueField = (label) => properties().getByRole('textbox', { name: `${label} value`, exact: true })
const addNode = async (label) => { await page.getByRole('button', { name: 'Add', exact: true }).click(); await page.getByRole('combobox', { name: 'Add a node' }).fill(label); await page.locator(`[role=option][data-label="${label}"]`).first().click() }
const picture = (title) => node(title).getByTestId('card-picture')
/** The drawn curve of a card's picture: every path, as text, so any change shows. */
const drawn = async (title) => (await picture(title).locator('path, rect, circle').evaluateAll((els) => els.map((el) => el.outerHTML))).join('|')
const sockets = () => page.getByRole('checkbox', { name: 'Sockets' })
const wireCount = () => surface.locator('[data-testid^="wire-"]').count()

await page.goto('http://localhost:4173/?starter')
await page.evaluate(async () => { localStorage.clear(); await new Promise((r) => { const q = indexedDB.deleteDatabase('sfxlab'); q.onsuccess = q.onerror = q.onblocked = () => r() }) })
await page.reload()
await track('Bass')
await page.getByRole('separator', { name: 'Resize editor' }).focus()
for (let i = 0; i < 40; i++) await page.keyboard.press('ArrowUp')

// ---- which cards have a picture
for (const title of ['Oscillator', 'Filter', 'Envelope', 'Gain', 'Delay']) check(`the ${title} card has a picture`, (await picture(title).count()) === 1)
for (const title of ['Note', 'Output']) check(`the ${title} card has none`, (await picture(title).count()) === 0)
await page.screenshot({ path: `${dir}/previews-cards.png` })

// ---- a picture follows the settings
const filterBefore = await drawn('Filter')
await selectNode('Filter')
await valueField('Cutoff').fill('200')
check('the Filter\'s picture moves with its cutoff', (await drawn('Filter')) !== filterBefore)
await properties().getByRole('combobox', { name: 'Mode', exact: true }).selectOption('1')
check('and with its mode', (await drawn('Filter')) !== filterBefore)
const oscBefore = await drawn('Oscillator')
await selectNode('Oscillator')
await properties().getByRole('combobox', { name: 'Wave', exact: true }).selectOption('2')
const square = await drawn('Oscillator')
check('the Oscillator draws its wave', square !== oscBefore)
await valueField('Freq').fill('2000')
check('and more cycles at a higher pitch', (await drawn('Oscillator')) !== square)
await selectNode('Envelope')
const envBefore = await drawn('Envelope')
await valueField('Attack').fill('1')
check('the Envelope draws its attack', (await drawn('Envelope')) !== envBefore)
await selectNode('Gain')
const gainBefore = await drawn('Gain')
await valueField('Gain').fill('0.1')
check('the Gain draws its level', (await drawn('Gain')) !== gainBefore)
await selectNode('Delay')
const delayBefore = await drawn('Delay')
await valueField('Feedback').fill('0.9')
check('the Delay draws its echoes', (await drawn('Delay')) !== delayBefore)

// ---- a wire into a socket: the picture follows the control
await sockets().check()
await (await page.getByTestId(`in-${await idOf('Filter')}-param:cutoff`)).click({ button: 'right' })
await page.getByRole('menuitem', { name: 'Create knob' }).click()
const wired = await drawn('Filter')
check('wiring a control that holds the same value does not change the picture', wired === (await drawn('Filter')))
await selectNode('Cutoff')
await valueField('Value').fill('8000')
check('turning the knob moves the Filter\'s picture (a wire resolves to the control\'s value)', (await drawn('Filter')) !== wired)
check('and the knob has no picture of its own', (await picture('Cutoff').count()) === 0)

// ---- a moving signal cannot be drawn: it says so
await addNode('LFO')
const lfoOut = await page.getByTestId(`out-${await idOf('LFO')}-out`).boundingBox()
const resSocket = await page.getByTestId(`in-${await idOf('Filter')}-param:resonance`).boundingBox()
await page.mouse.move(lfoOut.x + lfoOut.width - 4, lfoOut.y + lfoOut.height / 2)
await page.mouse.down()
await page.mouse.move(resSocket.x + 6, resSocket.y + resSocket.height / 2, { steps: 8 })
await page.mouse.up()
check('an LFO wired into a setting marks the picture as moving', (await picture('Filter').getAttribute('data-moving')) === 'true' && (await picture('Filter').getByText('~').count()) === 1)
check('and the LFO has a picture of its own', (await picture('LFO').count()) === 1)
await page.screenshot({ path: `${dir}/previews-wired.png` })

// ---- layout and persistence
const box = await node('Filter').boundingBox()
const ports = await node('Filter').locator('[data-port]').last().boundingBox()
check('the picture sits below the ports, inside the card', ports.y + ports.height <= box.y + box.height && (await picture('Filter').boundingBox()).y >= ports.y + ports.height - 2)
await page.waitForTimeout(800)
await page.reload()
await track('Bass')
check('the pictures are there after a reload, drawn from the saved values', (await picture('Filter').count()) === 1 && (await picture('Oscillator').count()) === 1)
check('no page errors', errors.length === 0, errors.join(' | '))
await browser.close()
