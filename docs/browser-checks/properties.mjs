import { createRequire } from 'node:module'
import { paramCount } from './registry.mjs'
import { existsSync } from 'node:fs'
const require = createRequire(existsSync('/node-tools/node_modules/') ? '/node-tools/node_modules/' : '/opt/node-tools/node_modules/')
const { chromium } = require('playwright')
const dir = process.argv[2] ?? '.'
const FILTER_PARAMS = await paramCount('filter')
const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium', args: ['--no-sandbox', '--autoplay-policy=no-user-gesture-required'] })
const context = await browser.newContext({ viewport: { width: 1500, height: 1000 } })
const page = await context.newPage()
const errors = []
page.on('pageerror', (e) => errors.push(String(e)))
page.on('console', (m) => m.type() === 'error' && errors.push(m.text()))
const check = (label, ok, extra = '') => console.log(`${ok ? 'PASS' : 'FAIL'}  ${label} ${extra}`)

const level = async (ms) => { let m = 0; const end = Date.now() + ms; while (Date.now() < end) { m = Math.max(m, Number(await page.locator('[data-peak]').first().getAttribute('data-peak'))); await page.waitForTimeout(30) } return m }
const surface = page.getByTestId('patch-surface')
const track = (name) => page.locator('[class*="_trackName_"]', { hasText: name }).first().click()
const nodes = () => surface.locator('[data-testid^="node-"]')
const node = (title) => nodes().filter({ has: page.locator('[class*="nodeTitle"]', { hasText: new RegExp(`^${title}`) }) }).first()
const idOf = async (title) => (await node(title).getAttribute('data-testid')).replace(/^node-/, '')
const properties = () => page.getByRole('complementary', { name: 'Properties' })
const selectNode = (title) => node(title).locator('[class*="nodeHeader"]').first().click()
const slider = (label) => properties().getByRole('slider', { name: label, exact: true })
const field = (label) => properties().getByRole('textbox', { name: `${label} value`, exact: true })
const row = (param) => properties().locator(`[data-param="${param}"]`)
const wireCount = () => surface.locator('[data-testid^="wire-"]').count()
const socket = async (title, param) => page.getByTestId(`in-${await idOf(title)}-param:${param}`)
const menuItem = (name) => page.getByRole('menuitem', { name, exact: true })
const sockets = () => page.getByRole('checkbox', { name: 'Sockets' })
const undo = () => page.getByRole('button', { name: 'Undo' }).click()

await page.goto('http://localhost:4173/?starter')
await page.evaluate(async () => { localStorage.clear(); await new Promise((r) => { const q = indexedDB.deleteDatabase('sfxlab'); q.onsuccess = q.onerror = q.onblocked = () => r() }) })
await page.reload()
await track('Bass')
const wiresBefore = await wireCount()
const nodesBefore = await nodes().count()

// ---- cards are only a title and sockets
check('a card has no slider, field, picker or switch on it', (await surface.locator('input, select, textarea').count()) === 0)
check('and no button but the remove button', (await surface.locator('[data-testid^="node-"] button').count()) === nodesBefore)
check('with nothing selected the editor says what to do', /Select a node/.test(await properties().innerText()))

// ---- selecting
await selectNode('Filter')
check('selecting a card shows its settings', /FILTER/i.test(await properties().innerText()) && (await row('cutoff').count()) === 1)
check('one row per parameter', (await properties().locator('[data-param]').count()) === FILTER_PARAMS)
await node('Gain').locator('[class*="nodeHeader"]').first().click({ modifiers: ['Shift'] })
check('two selected: a count, not settings', /2 nodes selected/.test(await properties().innerText()) && (await properties().locator('[data-param]').count()) === 0)
await node('Gain').locator('[class*="nodeHeader"]').first().click()
check('a click on the card body selects it too', await (async () => { await node('Delay').locator('[class*="ports"]').first().click({ position: { x: 90, y: 4 } }); return /DELAY/i.test(await properties().innerText()) })())

// ---- the name
await selectNode('Filter')
const nameField = properties().getByRole('textbox', { name: 'Name', exact: true })
check('the name field hints the default', (await nameField.getAttribute('placeholder')) === 'Filter')
await nameField.fill('Bright filter ')
await nameField.press('Enter')
check('naming a node renames its card (trimmed)', (await node('Bright filter').count()) === 1 && (await node('Filter').count()) === 0)
await undo()
check('and undo puts the old title back', (await node('Filter').count()) === 1)
await page.getByRole('button', { name: 'Redo' }).click()
await nameField.fill('')
await nameField.press('Enter')
check('clearing the name goes back to the default', (await node('Filter').count()) === 1)

// ---- values: field, slider, reset, clamp
await selectNode('Gain')
check('the Gain row shows its stored value', (await field('Gain').inputValue()) === '0.3')
await page.getByRole('button', { name: /^[▶■]\s*Root/ }).click()
await page.waitForTimeout(1500)
const loud = await level(1500)
check('the bass plays', loud > 0.02, loud.toFixed(3))
await slider('Gain').fill('0')
await page.waitForTimeout(1800)
const quiet = await level(1000)
check('the slider in the property editor sets the real parameter (Gain 0 is silent)', quiet < 0.005, quiet.toFixed(4))
await properties().getByRole('button', { name: 'Reset Gain' }).click()
check('reset puts the default back', (await field('Gain').inputValue()) === '1')
await page.waitForTimeout(1200)
check('and the sound with it', (await level(1500)) > 0.02)
await page.waitForTimeout(1000) // a pause ends the merge: what follows is its own undo step
await field('Gain').fill('99')
check('a typed value is held inside the range (the slider shows the stored 2)', (await slider('Gain').inputValue()) === '1000')
await field('Gain').blur()
check('and leaving the field shows the stored value, not what was typed', (await field('Gain').inputValue()) === '2')
await field('Gain').fill('-')
check('half-typed text is not applied', (await field('Gain').inputValue()) === '-')
await field('Gain').press('Escape')
check('Escape puts the stored value back', (await field('Gain').inputValue()) === '2')
await page.waitForTimeout(1000)
await field('Gain').click()
await field('Gain').press('Control+A')
await page.keyboard.type('0.75', { delay: 60 })
await page.keyboard.press('Enter')
check('typing a number sets it', (await field('Gain').inputValue()) === '0.75')
await undo()
check('typing is one undo step', (await field('Gain').inputValue()) === '2', await field('Gain').inputValue())

// ---- enum and switches
await selectNode('Filter')
await properties().getByRole('combobox', { name: 'Mode', exact: true }).selectOption('1')
check('an enum is a choice', (await properties().getByRole('combobox', { name: 'Mode', exact: true }).inputValue()) === '1')
await properties().getByRole('checkbox', { name: 'Stereo' }).check()
check('the stereo switch is in the editor, and the card shows an L R tag', (await node('Filter').locator('[class*="stereoTag"]').count()) === 1)
await properties().getByRole('checkbox', { name: 'Stereo' }).uncheck()
check('switching a node back to mono drops the stereo wire that no longer fits', (await wireCount()) < wiresBefore)
await undo() // the switch back to mono
await undo() // the switch to stereo
check('undo brings the wires the switch removed back', (await wireCount()) === wiresBefore)
await properties().getByRole('combobox', { name: 'Mode', exact: true }).selectOption('0')

// ---- right-click on a socket: create a knob
await sockets().check()
const levelBefore = await level(1500)
await (await socket('Filter', 'cutoff')).click({ button: 'right' })
check('a parameter socket offers Create knob and Create slider', (await menuItem('Create knob').count()) === 1 && (await menuItem('Create slider').count()) === 1 && (await menuItem('Disconnect').count()) === 0)
await page.screenshot({ path: `${dir}/properties-menu.png` })
await menuItem('Create knob').click()
check('Create knob adds a control and wires it (one node, one wire)', (await nodes().count()) === nodesBefore + 1 && (await wireCount()) === wiresBefore + 1)
check('it is named after the parameter and selected', (await node('Cutoff').count()) === 1 && (await node('Cutoff').getAttribute('data-selected')) === 'true')
check('with the parameter\'s range, unit and value', (await field('Value').inputValue()) === '700' && (await field('Min').inputValue()) === '20' && (await field('Max').inputValue()) === '20000' && (await properties().getByRole('textbox', { name: 'Unit', exact: true }).inputValue()) === 'Hz')
check('and a log curve for a frequency', (await properties().getByRole('combobox', { name: 'Curve', exact: true }).inputValue()) === '1')
await page.waitForTimeout(800)
const levelAfter = await level(1500)
check('the sound is the same: the control holds the value the parameter had', levelAfter > levelBefore * 0.7 && levelAfter < levelBefore * 1.4, `${levelBefore.toFixed(3)} -> ${levelAfter.toFixed(3)}`)
await page.screenshot({ path: `${dir}/properties-control.png` })
await selectNode('Filter')
check('the Cutoff row now says it is driven, and its field is off', /Driven by Cutoff/.test(await row('cutoff').innerText()) && (await field('Cutoff').isDisabled()))
await selectNode('Cutoff')
await slider('Value').fill('900')
await page.waitForTimeout(1000)
check('turning the knob changes the value the Filter is driven by, not the stored one', (await field('Value').inputValue()) !== '700')
await undo()
await undo()
check('undo takes the knob\'s value, then the whole knob and its wire, back', (await nodes().count()) === nodesBefore && (await wireCount()) === wiresBefore, `${await nodes().count()} nodes ${await wireCount()} wires`)

// ---- the rest of the menu
await (await socket('Filter', 'resonance')).click({ button: 'right' })
await menuItem('Create slider').click()
await selectNode('Res')
check('Create slider makes a slider display', (await properties().getByRole('combobox', { name: 'Display', exact: true }).inputValue()) === 'slider')
await (await socket('Filter', 'resonance')).click({ button: 'right' })
check('a wired socket offers Disconnect, and no second control', (await menuItem('Disconnect').count()) === 1 && (await menuItem('Create knob').count()) === 0)
await menuItem('Disconnect').click()
check('Disconnect removes the wire', (await wireCount()) === wiresBefore)
await selectNode('Filter')
check('and the row is its own again', (await row('resonance').getAttribute('data-driven')) === 'false' && !(await field('Res').isDisabled()))
const inPort = page.getByTestId(`in-${await idOf('Gain')}-in`)
await inPort.click({ button: 'right' })
check('an ordinary input that is wired offers only Disconnect', (await menuItem('Disconnect').count()) === 1 && (await menuItem('Create knob').count()) === 0)
await page.keyboard.press('Escape')
await (await socket('Gain', 'gain')).click({ button: 'right' })
await page.keyboard.press('Escape')
await page.getByTestId(`in-${await idOf('Oscillator')}-pitch`).click({ button: 'right' })
check('an ordinary input that is not wired has no menu', (await page.getByRole('menu').count()) === 0)

// ---- a button in the editor does the same
await selectNode('Filter')
await properties().getByRole('button', { name: 'Create knob for Res' }).click()
check('Create knob in the editor row makes the same thing', (await node('Res').count()) >= 1 && (await wireCount()) === wiresBefore + 1)
await selectNode('Filter')
await properties().getByRole('button', { name: 'Unwire Res' }).click()
check('Unwire removes it', (await wireCount()) === wiresBefore)

// ---- control settings: unit, display, range
await selectNode('Res')
await properties().getByRole('textbox', { name: 'Unit', exact: true }).fill('Q')
await properties().getByRole('textbox', { name: 'Unit', exact: true }).press('Enter')
check('a unit is shown beside the values', /Q/.test(await row('value').innerText()))
await properties().getByRole('combobox', { name: 'Display', exact: true }).selectOption('slider-horizontal')
await field('Max').fill('5')
check('the Value slider follows the control\'s own range (max 5)', (await slider('Value').getAttribute('max')) === '1000')
await field('Value').fill('9')
await field('Value').blur()
check('and the value is held inside it', (await field('Value').inputValue()) === '5', await field('Value').inputValue())

// ---- persistence
await page.waitForTimeout(800)
await page.reload()
await track('Bass')
await selectNode('Res')
check('name, unit, display and range survive a reload', (await properties().getByRole('textbox', { name: 'Unit', exact: true }).inputValue()) === 'Q' && (await properties().getByRole('combobox', { name: 'Display', exact: true }).inputValue()) === 'slider-horizontal' && (await field('Max').inputValue()) === '5')

check('no page errors', errors.length === 0, errors.join(' | '))
await browser.close()
