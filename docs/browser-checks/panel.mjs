const after = await position('Cutoff')
check('dragging a knob up raises it by the pixels dragged (45 of 180 = 0.25)', near(after - before, 0.25, 0.02), `${before} -> ${after}`)
const textAfter = await readout('Cutoff').textContent()
check('its readout follows, with the unit', textAfter !== textBefore && /Hz/.test(textAfter), `${textBefore} -> ${textAfter}`)
await view('Graph')
await selectNode('Cutoff')
check('the graph\'s property editor shows the same value on the Control node', Math.abs(parseFloat(await valueField('Value').inputValue()) - parseFloat(textAfter)) < 1, `${await valueField('Value').inputValue()} vs ${textAfter}`)
await view('Panel')

// ---- one drag is one undo step
