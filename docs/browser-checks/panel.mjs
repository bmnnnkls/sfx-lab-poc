check('in the graph they are Control nodes, wired into the parameters\' sockets', (await nodeCount()) === nodes0 + 2 && (await wireCount()) === wires0 + 2 && (await node('Cutoff').count()) === 1)
await view('Panel')

// ---- a knob sets the node's value
const before = await position('Cutoff')
const readout = (name) => page.locator('[data-testid^="control-"]').filter({ has: slider(name) }).locator('output')
check('the Cutoff knob starts where the parameter was (700 Hz on a log scale)', before > 0.4 && before < 0.8 && /700/.test(await readout('Cutoff').textContent()), `${before} ${await readout('Cutoff').textContent()}`)
