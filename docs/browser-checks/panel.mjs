check('Panel replaces the graph, and the canvas-only buttons go', (await page.getByTestId('front-panel').count()) === 1 && (await page.getByTestId('patch-surface').count()) === 0 && (await page.getByRole('button', { name: /^Group into module/ }).count()) === 0)
check('a patch with no control nodes says so', (await page.getByText('This patch has no controls yet.').count()) === 1)
check('and there is no "Build from graph": the panel is the control nodes', (await page.getByRole('button', { name: 'Build from graph' }).count()) === 0)

// ---- add knobs: each is a control node wired to the parameter
